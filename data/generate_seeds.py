def culinary(**kwargs) -> MushroomProfile:
    kwargs.setdefault("pack", "culinary")
    kwargs.setdefault("restricted", False)
    kwargs.setdefault("affiliates_allowed", True)
    kwargs.setdefault("pricing", Pricing())
    kwargs.setdefault("affiliate_links", [EXAMPLE_SPAWN, EXAMPLE_SUBSTRATE])
    return validate_profile(MushroomProfile(**kwargs))


def psi(**kwargs) -> MushroomProfile:
    kwargs.setdefault("pack", "psilocybin")
    kwargs.setdefault("restricted", True)
    kwargs.setdefault("affiliates_allowed", False)
    kwargs.setdefault("affiliate_links", [])
    kwargs.setdefault("allowed_payment_providers", [])
    kwargs.setdefault("pricing", Pricing())
    kwargs.setdefault("legal_notice", PSILOCYBIN_LEGAL_NOTICE)
    kwargs.setdefault("tags", [])
    tags = list(kwargs["tags"])
    if "psilocybin" not in tags:
        tags.append("psilocybin")
    kwargs["tags"] = tags
    return validate_profile(MushroomProfile(**kwargs))


