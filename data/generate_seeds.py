def main() -> None:
    profiles = build_profiles()
    culinary_dir = ROOT / "profiles" / "culinary"
    psi_dir = ROOT / "profiles" / "psilocybin"
    culinary_dir.mkdir(parents=True, exist_ok=True)
    psi_dir.mkdir(parents=True, exist_ok=True)
    for old in list(culinary_dir.glob("*.json")) + list(psi_dir.glob("*.json")):
        old.unlink()
    for profile in profiles:
        dest_dir = psi_dir if profile.pack == "psilocybin" else culinary_dir
        path = dest_dir / f"{profile.id}.json"
        path.write_text(json.dumps(profile.to_dict(), indent=2) + "\n", encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT.parent)}")
    print(f"total {len(profiles)} profiles")


if __name__ == "__main__":
    main()
