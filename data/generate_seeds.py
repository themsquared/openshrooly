def light(hours: float, lux: int, sunrise: int = 8, blue: int = 0) -> LightSchedule:
    return LightSchedule(
        sunrise_hour=sunrise,
        duration_hours=hours,
        white_led_lux=lux,
        blue_percent=blue,
    )


def fan(period: int, run: int, speed: int) -> FanSchedule:
    return FanSchedule(period_min=period, run_duration_s=run, speed_percent=speed)


def stage(
    stage_id: str,
    name: str,
    days: float,
    rh: float,
    temp: float,
    *,
    light_hours: float = 0,
    lux: int = 0,
    fan_period: int = 60,
    fan_run: int = 15,
    fan_speed: int = 20,
    rh_hyst: float = 2.0,
    temp_hyst: float = 1.0,
    warn_min: float | None = None,
    warn_max: float | None = None,
    humid_speed: float = 75,
    notes: str = "",
    blue: int = 0,
) -> ProfileStage:
    return ProfileStage(
        id=stage_id,
        name=name,
        duration_days=days,
        humidity_percent=rh,
        temperature_c=temp,
        humidity_hysteresis=rh_hyst,
        temperature_hysteresis=temp_hyst,
        temperature_warning_min_c=warn_min if warn_min is not None else max(10, temp - 5),
        temperature_warning_max_c=warn_max if warn_max is not None else min(35, temp + 5),
        humidifier_speed_percent=humid_speed,
        light=light(light_hours, lux, blue=blue),
        fan=fan(fan_period, fan_run, fan_speed),
        notes=notes,
    )


def src(title: str, detail: str, url: str | None = None) -> SourceNote:
    return SourceNote(title=title, detail=detail, url=url)


